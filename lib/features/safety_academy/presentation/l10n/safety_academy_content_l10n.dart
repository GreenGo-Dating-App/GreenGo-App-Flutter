// Localization of the bundled Safety Academy content.
//
// The seed content (SafetyAcademySeedData) keeps stable module/lesson ids
// (stored user progress references them). Displayed text is looked up here
// by id (+ section/question/option index); anything without a translation
// key (e.g. a module added server-side later) falls back to the stored text.
//
// The lookup table below is generated from the seed data
// (C:/dev/i18n-tools/sa_work/gen_dart.py during the i18n sweep); keep it in
// sync when seed content changes.

