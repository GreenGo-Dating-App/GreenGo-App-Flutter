/// Localized copy of [module] (title/description), falling back to the
/// stored text for unknown ids.
SafetyModule localizedSafetyModule(AppLocalizations l10n, SafetyModule module) {
  return SafetyModule(
    id: module.id,
    title: _text(l10n, '${module.id}.title') ?? module.title,
    description:
        _text(l10n, '${module.id}.description') ?? module.description,
    iconName: module.iconName,
    lessons: module.lessons,
    order: module.order,
    xpReward: module.xpReward,
  );
}

/// Localized copy of [lesson] including its content sections and quiz.
SafetyLesson localizedSafetyLesson(AppLocalizations l10n, SafetyLesson lesson) {
  final id = lesson.id;
  final sections = <LessonContent>[];
  for (var i = 0; i < lesson.contentSections.length; i++) {
    final s = lesson.contentSections[i];
    sections.add(LessonContent(
      type: s.type,
      content: _text(l10n, '$id.s$i') ?? s.content,
      items: [
        for (var j = 0; j < s.items.length; j++)
          _text(l10n, '$id.s$i.i$j') ?? s.items[j],
      ],
    ));
  }
  final quiz = lesson.quiz;
  return SafetyLesson(
    id: id,
    moduleId: lesson.moduleId,
    title: _text(l10n, '$id.title') ?? lesson.title,
    contentSections: sections,
    quiz: quiz == null ? null : localizedSafetyQuiz(l10n, id, quiz),
    xpReward: lesson.xpReward,
    order: lesson.order,
  );
}

/// Localized copy of [quiz] belonging to the lesson [lessonId].
SafetyQuiz localizedSafetyQuiz(
  AppLocalizations l10n,
  String lessonId,
  SafetyQuiz quiz,
) {
  return SafetyQuiz(
    id: quiz.id,
    lessonId: quiz.lessonId,
    passingScore: quiz.passingScore,
    questions: [
      for (var i = 0; i < quiz.questions.length; i++)
        QuizQuestion(
          question:
              _text(l10n, '$lessonId.q$i') ?? quiz.questions[i].question,
          options: [
            for (var j = 0; j < quiz.questions[i].options.length; j++)
              _text(l10n, '$lessonId.q$i.o$j') ??
                  quiz.questions[i].options[j],
          ],
          correctIndex: quiz.questions[i].correctIndex,
          explanation: _text(l10n, '$lessonId.q$i.exp') ??
              quiz.questions[i].explanation,
        ),
    ],
  );
}

